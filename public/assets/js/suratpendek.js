let currentQuiz = [];
let quizIndex = 0;
let score = 0;

function startQuiz(){

currentQuiz = quizData[currentSurat.judul];

if(!currentQuiz){

alert(
"Quiz untuk surat " +
currentSurat.judul +
" belum tersedia"
);

return;
}

quizIndex = 0;
score = 0;

document.getElementById("quizPopup")
.classList.add("show");

showQuiz();
}

function showQuiz(){

const q = currentQuiz[quizIndex];

document.getElementById("quizQuestion").innerText = q.question;
document.getElementById("quizScore").innerText = "Skor: " + score;

const audioBtn = document.getElementById("quizAudioBtn");

if(q.audio){
  audioBtn.style.display = "inline-block";
  audioBtn.innerHTML = "🔊 Dengarkan Audio";
}else{
  audioBtn.style.display = "none";
  audioBtn.innerHTML = "";
}

const optionBox = document.getElementById("quizOptions");
optionBox.innerHTML = "";

q.options.forEach(option=>{
  const btn = document.createElement("button");
  btn.className = "quiz-option";
  btn.innerText = option;
  btn.onclick = ()=>checkAnswer(btn, option);
  optionBox.appendChild(btn);
});

}

function checkAnswer(button, selected){

const correct =
currentQuiz[quizIndex].answer;

const allButtons =
document.querySelectorAll(".quiz-option");

allButtons.forEach(btn=>{
btn.disabled = true;

if(btn.innerText === correct){
btn.classList.add("correct");
}

if(
btn.innerText === selected &&
selected !== correct
){
btn.classList.add("wrong");
}
});

if(selected === correct){
score += 20;
}

setTimeout(()=>{

quizIndex++;

if(quizIndex < currentQuiz.length){

showQuiz();

}else{

document.getElementById("quizAudioBtn")
.style.display = "none";

document.getElementById("quizQuestion")
.innerHTML =
"🎉 Horeee Quiz Selesai!";

document.getElementById("quizOptions")
.innerHTML =
"<h3>Skor Kamu: " + score + "</h3>";

}

},1000);

}


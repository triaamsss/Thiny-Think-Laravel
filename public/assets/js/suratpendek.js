function playAudio(){
const ayat = currentSurat.ayat[index];
if(!ayat.audio){
  alert("Audio belum ada");
  return;
}
const player = document.getElementById("audioPlayer");
const btn = document.getElementById("playBtn");
if(isAudioPlaying){

  player.pause();

  isAudioPlaying = false;

  btn.innerHTML = "🔇";

}else{

  player.src = ayat.audio;

  player.load();

  player.play();

  isAudioPlaying = true;

  btn.innerHTML = "🔊";

}

}


let currentSurat=null;
let index=0;
let artiVisible=true;
let isAudioPlaying = false;

function render(){
const list=document.getElementById("list");
list.innerHTML="";
suratData.forEach((s,i)=>{
const item=document.createElement("div");
item.className="surat-item";
item.innerHTML=`
<div class="surat-left">
<div class="icon">
  <img src="/assets/images/slider/logo quran.png" class="surat-icon">
</div>
<div>
<div class="arab">${s.arabTitle}</div>
<div class="latin">${s.judul}</div>
</div>
</div>
<div class="play">▶</div>`;
item.onclick=()=>openModal(i);
list.appendChild(item);
});
}

function openModal(i){
currentSurat = suratData[i];
index = 0;
update();
document.getElementById("modal")
.classList.add("show");
}

function closeModal(){
document.getElementById("modal").classList.remove("show");
}

function update(){
const ayat=currentSurat.ayat[index];

document.getElementById("title").innerHTML=
currentSurat.arabTitle+"<br><small>"+currentSurat.judul+"</small>";

const totalAyat = currentSurat.ayat.filter(a => a.no !== "").length;

document.getElementById("suratTotal").innerText =
"📖 " + totalAyat + " Ayat";

document.getElementById("ayatNo").innerText =
ayat.no ? "Ayat " + ayat.no : "";

document.getElementById("arab").innerHTML =
ayat.arab +

(ayat.no
? " <span dir='ltr' class='ayat-symbol'>" + toArabicNumber(ayat.no) + "</span>"
: "");
  document.getElementById("latin").innerText=ayat.latin;
  document.getElementById("arti").innerText=ayat.arti;
}

function nextAyat(){
if(index < currentSurat.ayat.length - 1){
  index++;
  update();
  isAudioPlaying = false;
document.getElementById("playBtn")
.innerHTML = "🔇";
}else{
  document.getElementById("finishPopup")
  .classList.add("show");
  document.getElementById("finishText")
  .innerText =
  "Horeee kamu telah menyelesaikan surat " +
  currentSurat.judul + " 🎉🌈";
}
}
function prevAyat(){
if(index > 0){
index--;
update();

isAudioPlaying = false;

document.getElementById("playBtn")
.innerHTML = "🔇";

}else{
alert("Ini ayat pertama 😊");
}
}

function toggleArti(){
artiVisible=!artiVisible;
document.getElementById("arti").style.display=artiVisible?"block":"none";
}

function toArabicNumber(num){
  const arabicNums = ['٠','١','٢','٣','٤','٥','٦','٧','٨','٩'];
  return num.toString().split('').map(d => arabicNums[d]).join('');
}

function closeFinishPopup(){
  document.getElementById("finishPopup")
  .classList.remove("show");
}
